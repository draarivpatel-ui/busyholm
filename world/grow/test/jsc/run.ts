// WP-08 determinism check, JavaScriptCore half: grow() must give byte-identical worlds in JavaScriptCore,
// the engine inside WKWebView (the macOS app's webview), the same as Node (V8) and Chrome (V8) already do.
//
// Usage (from world/grow):  node test/jsc/run.ts [master] [count]
// Exit:  0 digests match, 1 mismatch, grow() error or harness error, 2 the jsc binary is missing.
//
// How modules reach jsc: the jsc shell runs ES modules from disk but does not strip TypeScript, and it
// rejects a .ts file even when the code in it is valid TypeScript (checked). So every package file that
// test/cases.ts, src/grow.ts and src/canonical.ts need at runtime is copied to a fresh temp dir with its
// types stripped (node:module stripTypeScriptTypes, mode "strip"), renamed from .ts to .js, and its
// "./x.ts" import specifiers rewritten to "./x.js". The relative layout is kept. A generated entry module
// (master and count baked in as literals) prints one canonical World per line; this script hashes those
// lines and compares with hashWorlds() run in Node.
import { spawnSync } from "node:child_process";
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { stripTypeScriptTypes } from "node:module";
import { tmpdir } from "node:os";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { DETERMINISM_COUNT, DETERMINISM_MASTER, determinismInput } from "../cases.ts";
import { canonicalJson } from "../../src/canonical.ts";
import { grow } from "../../src/grow.ts";
import { hashWorlds } from "../hash-worlds.ts";

const JSC = "/System/Library/Frameworks/JavaScriptCore.framework/Versions/Current/Helpers/jsc";
const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(HERE, "..", "..");
// Everything the entry module imports at runtime; the walk below adds whatever those files import.
const ENTRY_ROOTS = ["test/cases.ts", "src/grow.ts", "src/canonical.ts"];
const JSC_TIMEOUT_MS = 240_000;
const JSC_MAX_BUFFER = 512 * 1024 * 1024;

const sha = (s: string): string => createHash("sha256").update(s).digest("hex");
const msg = (e: unknown): string => (e instanceof Error ? e.message : String(e));
const trunc = (s: string): string => (s.length > 2000 ? s.slice(0, 2000) + `... [${s.length - 2000} more chars]` : s);

// Import/export specifiers that survive stripping (type-only imports are removed before this runs).
const IMPORT_SPEC = /\b(?:from|import)\s*(["'])([^"'\n]+)\1/g;

interface StrippedModule {
  readonly rel: string;
  readonly js: string;
}

/** Strips every reachable module, failing if one needs a bare package at runtime. */
function collectModules(): StrippedModule[] {
  const out = new Map<string, string>();
  const queue = [...ENTRY_ROOTS];
  while (queue.length > 0) {
    const rel = queue.shift()!;
    if (out.has(rel)) continue;
    const abs = join(ROOT, rel);
    if (!existsSync(abs)) throw new Error(`module ${rel} does not exist under ${ROOT}`);
    const js = stripTypeScriptTypes(readFileSync(abs, "utf8"), { mode: "strip" });
    out.set(rel, js);
    for (const m of js.matchAll(IMPORT_SPEC)) {
      const spec = m[2]!;
      if (!spec.startsWith("./") && !spec.startsWith("../")) {
        throw new Error(
          `${rel} needs the bare package "${spec}" at runtime; jsc cannot resolve packages, so it cannot run here`,
        );
      }
      if (!spec.endsWith(".ts")) throw new Error(`${rel} imports "${spec}", which does not end in .ts`);
      queue.push(relative(ROOT, resolve(dirname(join(ROOT, rel)), spec)));
    }
  }
  return [...out].map(([rel, js]) => ({ rel, js }));
}

/** Writes the stripped modules under tmp as .js, same layout, with "./x.ts" specifiers rewritten to "./x.js". */
function writeModules(tmp: string, modules: readonly StrippedModule[]): void {
  for (const { rel, js } of modules) {
    const out = join(tmp, rel.replace(/\.ts$/, ".js"));
    mkdirSync(dirname(out), { recursive: true });
    writeFileSync(out, js.replace(/(\b(?:from|import)\s*)(["'])(\.\.?\/[^"'\n]+)\.ts\2/g, "$1$2$3.js$2"));
  }
}

function entrySource(master: number, count: number): string {
  return `// Generated by test/jsc/run.ts. Prints one canonical World per line; stops at the first grow() error.
import { determinismInput } from "./test/cases.js";
import { grow } from "./src/grow.js";
import { canonicalJson } from "./src/canonical.js";

for (let i = 0; i < ${count}; i++) {
  let line;
  try {
    const c = determinismInput(${master}, i);
    line = canonicalJson(grow(c.seed, c.ledger, c.choices, c.options));
  } catch (e) {
    print("ERROR " + i + " " + String(e && e.message ? e.message : e).replace(/\\s+/g, " "));
    break;
  }
  print(line);
}
`;
}

async function main(): Promise<number> {
  const master = process.argv[2] === undefined ? DETERMINISM_MASTER : Number(process.argv[2]);
  const count = process.argv[3] === undefined ? DETERMINISM_COUNT : Number(process.argv[3]);
  if (!Number.isInteger(master) || !Number.isInteger(count) || count < 1) {
    console.error(`ERROR: bad arguments (master=${process.argv[2]}, count=${process.argv[3]})`);
    return 1;
  }
  if (!existsSync(JSC)) {
    console.error(`SKIP: jsc not found at ${JSC} (this check needs macOS)`);
    return 2;
  }

  const tStart = performance.now();
  let tmp: string | undefined;
  try {
    tmp = mkdtempSync(join(tmpdir(), "grow-jsc-"));
    const modules = collectModules();
    writeModules(tmp, modules);
    const entry = join(tmp, "entry.mjs");
    writeFileSync(entry, entrySource(master, count));

    const tJsc = performance.now();
    const r = spawnSync(JSC, ["-m", entry], { encoding: "utf8", maxBuffer: JSC_MAX_BUFFER, timeout: JSC_TIMEOUT_MS });
    const jscMs = performance.now() - tJsc;
    const jscCmd = `${JSC} -m <tmp>/entry.mjs`;

    if (r.error !== undefined) {
      console.log(`FAIL: could not run jsc (${jscCmd}): ${msg(r.error)}`);
      return 1;
    }
    if (r.status !== 0) {
      console.log(`FAIL: jsc exited ${r.status ?? r.signal} (${jscCmd})`);
      console.log(`stdout:\n${trunc(r.stdout ?? "")}\nstderr:\n${trunc(r.stderr ?? "")}`);
      return 1;
    }
    if ((r.stderr ?? "").trim() !== "") {
      console.log(`FAIL: jsc wrote to stderr (${jscCmd}):\n${trunc(r.stderr)}`);
      return 1;
    }
    const lines = (r.stdout ?? "").split("\n");
    if (lines[lines.length - 1] === "") lines.pop();
    const errorLine = lines.find((l) => l.startsWith("ERROR "));
    if (errorLine !== undefined) {
      console.log(`FAIL: grow() threw in jsc: ${errorLine}`);
      return 1;
    }
    if (lines.length !== count) {
      console.log(`FAIL: jsc printed ${lines.length} worlds, expected ${count}`);
      return 1;
    }

    const jscHashes = lines.map(sha);
    const jscDigest = sha(jscHashes.join("\n"));

    let node: { digest: string; hashes: string[] };
    try {
      node = hashWorlds(master, count);
    } catch (e) {
      console.log(`FAIL: Node side grow() threw: ${msg(e)}`);
      return 1;
    }

    console.log(`master=${master} count=${count} node=${process.version}`);
    console.log(`jsc: ${JSC} -m entry.mjs (${jscMs.toFixed(0)} ms for ${count} worlds, ${(r.stdout ?? "").length} chars of output)`);
    console.log(`jsc digest:  ${jscDigest}`);
    console.log(`node digest: ${node.digest}`);

    if (jscDigest === node.digest && jscHashes.length === node.hashes.length) {
      console.log(`PASS: ${count} worlds byte-identical in JavaScriptCore and Node ${process.version} (total ${((performance.now() - tStart) / 1000).toFixed(1)} s)`);
      return 0;
    }

    let first = 0;
    while (first < jscHashes.length && first < node.hashes.length && jscHashes[first] === node.hashes[first]) first++;
    console.log(`FAIL: digests differ; first differing case index: ${first}`);
    if (first < lines.length && first < count) {
      const c = determinismInput(master, first);
      const nodeCanonical = canonicalJson(grow(c.seed, c.ledger, c.choices, c.options));
      console.log(`jsc canonical JSON:\n${trunc(lines[first]!)}`);
      console.log(`node canonical JSON:\n${trunc(nodeCanonical)}`);
    }
    return 1;
  } catch (e) {
    console.log(`FAIL: harness error: ${msg(e)}`);
    return 1;
  } finally {
    if (tmp !== undefined) rmSync(tmp, { recursive: true, force: true });
  }
}

process.exitCode = await main();
